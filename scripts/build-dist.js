'use strict';
/**
 * Static frontend build for Vercel (or any static host): public/ -> dist/.
 *
 *   CLAIMTRAIL_API_BASE_URL   PUBLIC origin of the Render API, e.g. https://claimtrail-api.onrender.com
 *                             (empty/unset = same-origin mode, for the Render-only monolith or local use).
 *
 * Guarantees (all asserted by test/build-dist.test.js):
 *  - the tracked public/config.js is never modified; dist/config.js is generated with a JSON-escaped origin;
 *  - the base must be an origin only (no path/credentials/query) - invalid values FAIL the build, never silently degrade;
 *  - dist/index.html gets a CSP <meta> whose connect-src is exactly 'self' + that one API origin;
 *  - every asset referenced by index.html and every relative ES-module import exists in dist/;
 *  - no server secret (SARVAM_API_KEY value, vendor header names, key-looking strings) can be present in dist/.
 */
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const ROOT = path.join(__dirname, '..');

const CSP = (connectExtra) => [
  "default-src 'self'", "script-src 'self'", "style-src 'self'", "img-src 'self' data:", `connect-src 'self'${connectExtra ? ' ' + connectExtra : ''}`,
  "object-src 'none'", "base-uri 'none'", "form-action 'self'",
].join('; ');

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else if (e.isFile()) fs.copyFileSync(s, d); // symlinks are ignored on purpose
  }
}
function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) { const p = path.join(dir, e.name); e.isDirectory() ? walk(p, out) : out.push(p); }
  return out;
}

async function buildDist({ apiBase = process.env.CLAIMTRAIL_API_BASE_URL, outDir = path.join(ROOT, 'dist'), srcDir = path.join(ROOT, 'public'), env = process.env } = {}) {
  const { normalizeApiBase } = await import(pathToFileURL(path.join(srcDir, 'api-base.mjs')).href);
  const base = normalizeApiBase(apiBase); // throws on anything but a clean origin
  if (path.resolve(outDir) === path.resolve(srcDir) || path.resolve(outDir) === ROOT) throw new Error('Refusing to use the source folder or repo root as the output directory.');
  fs.rmSync(outDir, { recursive: true, force: true });
  copyDir(srcDir, outDir);

  // generated config: the only thing that varies per deployment. JSON-escape, and neutralise "</script"-style sequences.
  const esc = (t) => t.replace(/</g, '\\u003c').split(String.fromCharCode(0x2028)).join('\\u2028').split(String.fromCharCode(0x2029)).join('\\u2029');
  const cfg = esc(JSON.stringify({ apiBaseUrl: base }));
  fs.writeFileSync(path.join(outDir, 'config.js'), `// Generated by scripts/build-dist.js. Public, non-secret deployment config.\nwindow.CLAIMTRAIL_CONFIG = Object.freeze(${cfg});\n`);

  // CSP for static hosting (meta cannot express frame-ancestors; vercel.json sends the other security headers).
  const htmlPath = path.join(outDir, 'index.html');
  let html = fs.readFileSync(htmlPath, 'utf8');
  if (!/<meta charset="utf-8">/i.test(html)) throw new Error('index.html is missing <meta charset>; cannot inject the CSP.');
  html = html.replace(/<meta charset="utf-8">/i, (m) => `${m}\n  <meta http-equiv="Content-Security-Policy" content="${CSP(base)}">`);
  fs.writeFileSync(htmlPath, html);

  verifyDist(outDir, env);
  return { outDir, apiBase: base, files: walk(outDir).length };
}

function verifyDist(outDir, env = process.env) {
  const problems = [];
  const exists = (rel) => fs.existsSync(path.join(outDir, rel));
  const html = fs.readFileSync(path.join(outDir, 'index.html'), 'utf8');
  for (const m of html.matchAll(/(?:src|href)="(\/[^"#?]+)"/g)) if (!exists(m[1].slice(1))) problems.push(`index.html references a missing file: ${m[1]}`);
  for (const f of walk(outDir).filter((p) => /\.(m?js)$/.test(p))) {
    const text = fs.readFileSync(f, 'utf8');
    for (const m of text.matchAll(/(?:from|import)\s*\(?\s*['"](\.\/[^'"]+)['"]/g)) if (!fs.existsSync(path.join(path.dirname(f), m[1]))) problems.push(`${path.relative(outDir, f)} imports a missing module: ${m[1]}`);
  }
  const secret = typeof env.SARVAM_API_KEY === 'string' && env.SARVAM_API_KEY.trim().length >= 8 ? env.SARVAM_API_KEY.trim() : null;
  for (const f of walk(outDir)) {
    const text = fs.readFileSync(f, 'utf8');
    const rel = path.relative(outDir, f);
    if (secret && text.includes(secret)) problems.push(`${rel} contains the SARVAM_API_KEY value`);
    if (/api-subscription-key/i.test(text)) problems.push(`${rel} mentions the vendor auth header (server-only)`);
    if (/\bsk[-_][A-Za-z0-9_-]{16,}/.test(text)) problems.push(`${rel} contains a key-looking string`);
    if (/SARVAM_API_KEY/.test(text)) problems.push(`${rel} mentions SARVAM_API_KEY`);
  }
  if (!exists('config.js')) problems.push('config.js is missing');
  if (problems.length) throw new Error('dist verification failed:\n - ' + problems.join('\n - '));
}

module.exports = { buildDist, verifyDist, CSP };

if (require.main === module) {
  buildDist().then((r) => console.log(`dist built: ${r.files} files in ${path.relative(ROOT, r.outDir) || '.'}; API base = ${r.apiBase || '(same origin)'}`))
    .catch((e) => { console.error('build:dist FAILED:', e.message); process.exit(1); });
}
